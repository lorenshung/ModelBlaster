#!/usr/bin/env python3
"""Emit a spike test that replays a generated backend's dispatches against golden tensors.

  gen_replay.py GEN BACKEND GOLDEN_DIR OUT.c [--ops kind,kind,...]

For every dispatch in GEN/graph.json whose op kind is selected (default: every kind
that does not run on Gemmini), the test copies the GOLDEN input tensors into the
dispatch's buffers, calls the generated dispatch function from GEN/BACKEND/model.c
(the real generated code: same pointers, same constants, same kernels.c), and
byte-compares the output buffer with the GOLDEN output tensor. Each dispatch is
isolated: its inputs come from the golden set, not from the previous dispatch, so a
failure points at one op.

GOLDEN_DIR is a directory with tensors/manifest.json (graph_tensor, file, layout) as
written by the RiskyBird golden model (soc-cache/p2goal/golden). Golden 4-D tensors
are NHWC; a graph tensor declared nchw is compared after permuting. A flattened
tensor carries its order in tensors[t]["flat_order"] (assign_layouts
--flatten-into-linear); golden `<name>` is NHWC-flatten, `<name>_nchw` NCHW-flatten.
"""
import argparse, json, os, sys

def c_ident(s): return s.replace(".", "_").replace("-", "_")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("gen"); ap.add_argument("backend"); ap.add_argument("golden"); ap.add_argument("out")
    ap.add_argument("--ops", default=None)
    a = ap.parse_args()
    g = json.load(open(os.path.join(a.gen, "graph.json")))
    man = json.load(open(os.path.join(a.golden, "tensors", "manifest.json")))
    gold = {}
    for t in man["tensors"]:
        gold.setdefault(t.get("graph_tensor") or t["name"], t)
        gold.setdefault(t["name"], t)
    tensors = g["tensors"]; mid = c_ident(g["name"])
    alias = {o["outputs"][0]: o["inputs"][0] for o in g["ops"] if o["op"] == "view" or o.get("elided")}
    def res(t):
        while t in alias: t = alias[t]
        return t
    ins = g["input"].get("tensors") or [g["input"]["tensor"]]
    outs = g["output"].get("tensors") or [g["output"]["tensor"]]
    sizes = {t: 1 for t in tensors}
    for t, v in tensors.items():
        for d in v.get("shape") or []: sizes[t] *= int(d)
    out_off = {}
    off = 0
    for t in outs: out_off[t] = off; off += sizes[t]
    def ptr(t):
        r = res(t)
        if r in ins: return "g_input"
        if r in out_off: return f"(g_output + {out_off[r]})"
        return f"buf_{mid}_{c_ident(r)}"
    sel = set(a.ops.split(",")) if a.ops else None
    skip = {"conv2d_s8", "conv2d_pool_s8"} if sel is None else set()
    blobs, rows, used = {}, [], {}
    def golden_for(t):
        """(manifest entry, permutation) for graph tensor t, or None."""
        meta = tensors.get(t, {})
        sh = meta.get("shape") or []
        r = res(t)
        if r != t and len(sh) == 2:          # a flatten view: the 4-D tensor's order
            t, meta, sh = r, tensors.get(r, {}), tensors.get(r, {}).get("shape") or []
        gm = gold.get(t)
        if gm is None and t.endswith(".nhwc"):   # an island boundary copy of tensor <t>
            gm = gold.get(t[:-5])
        if gm is None and r != t:            # a layout alias (assign_layouts --alias-c1)
            t, meta, sh = r, tensors.get(r, {}), tensors.get(r, {}).get("shape") or []
            gm = gold.get(t)
        if gm is None:
            return None
        if len(sh) == 4 and meta.get("layout", "nchw") != "nhwc" and int(sh[1]) != 1:
            return gm, ("nhwc2nchw", [int(v) for v in sh])
        if (len(sh) == 2 and str(gm.get("layout", "")).startswith("flat")
                and meta.get("flat_order") != "nhwc"):
            alt = gold.get(gm["name"] + "_nchw")
            return (alt, None) if alt else None
        return gm, None
    def blob(gm, perm):
        key = gm["name"] + ("" if perm is None else "_p")
        if key not in blobs:
            data = open(os.path.join(a.golden, gm["file"]), "rb").read()
            if perm is not None:
                _, (N, C, H, W) = perm
                data = bytes(data[(h * W + w) * C + c] for c in range(C) for h in range(H) for w in range(W))
            blobs[key] = data
        return "g_" + c_ident(key)
    for o in g["ops"]:
        d = o.get("dispatch_id")
        if d is None or o.get("elided"): continue
        k = o["op"]
        if (sel is not None and k not in sel) or k in skip: continue
        gi = [golden_for(t) for t in o["inputs"]]
        go = golden_for(o["outputs"][0])
        if any(x is None for x in gi) or go is None:
            print(f"  skip dispatch {d} {o['name']}: no golden for {o['inputs']} -> {o['outputs']}", file=sys.stderr)
            continue
        cin = [(ptr(t), blob(*x), sizes[res(t)] if res(t) in sizes else len(blobs)) for t, x in zip(o["inputs"], gi)]
        rows.append((d, o["name"], k, cin, ptr(o["outputs"][0]), blob(*go), sizes[o["outputs"][0]]))
    L = ["/* @generated by tests/riskybird_dronet/gen_replay.py */", "#include <stdint.h>", "#include <stdio.h>",
         "#include <string.h>", '#include "model.h"', '#include "weights.h"']
    seen = set()
    for r in rows:
        for p in [x[0] for x in r[3]] + [r[4]]:
            if p.startswith("buf_") and p not in seen:
                seen.add(p); L.append(f"extern int8_t {p}[];")
    insz = sum(sizes[t] for t in ins)
    L += [f"static int8_t g_input[{insz}] __attribute__((aligned(64)));", f"static int8_t g_output[{off}];"]
    for k, data in blobs.items():
        L.append(f"static const int8_t g_{c_ident(k)}[{len(data)}] = {{" + ",".join(str(b - 256 if b > 127 else b) for b in data) + "};")
    L += [f"extern const model_{mid}_dispatch_fn MODEL_{mid.upper()}_DISPATCH_FNS[];", "int main(void) {",
          f"    model_{mid}_state_t s; memset(&s, 0, sizeof s);",
          "    s.input = (void *)g_input; s.output = (void *)g_output;", "    int fails = 0, n = 0;"]
    for d, name, k, cin, op, gb, n in rows:
        for p, b, _ in cin:
            L.append(f"    memcpy({p}, {b}, sizeof {b});")
        L.append(f"    memset({op}, 0x5a, {n});")
        L.append(f"    MODEL_{mid.upper()}_DISPATCH_FNS[{d}](&s);")
        L.append(f"    {{ int bad = 0; for (int i = 0; i < {n}; i++) bad += ((int8_t *){op})[i] != {gb}[i]; n++; fails += bad != 0;"
                 f' printf("dispatch %2d %-16s %-18s %6d bytes: %s (%d differ)\\n", {d}, "{name}", "{k}", {n}, bad ? "DIFFER" : "IDENTICAL", bad); }}')
    L += ['    printf("REPLAY %s: %d/%d dispatches byte-identical to golden\\n", fails ? "FAIL" : "PASS", n - fails, n);',
          "    return fails != 0;", "}"]
    open(a.out, "w").write("\n".join(L) + "\n")
    print(f"wrote {a.out}: {len(rows)} dispatches")

main()
